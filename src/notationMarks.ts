export function defaultMarkPlace(code: ScoreMark['code']): ScoreMark['place'] {
  if (['breath', 'caesura', 'fluteZeng', 'fluteSlideDown', 'voiceBreath', 'fluteCircularBreath', 'suonaCircular'].includes(code)) return 'gap'
  if (Object.hasOwn(dynamics, code) || ['fp', 'sfz', 'sf', 'sfp', 'fz', 'subitoP', 'subitoF', 'pedalDown', 'pedalUp',
    'pedalHalf', 'pedalChange', 'softPedal', 'softPedalUp', 'sostenutoPedal', 'sostenutoPedalUp'].includes(code)) return 'below'
  return 'above'
}

export function pairedSpans<T>(beats: readonly T[], ends: (beat: T) => readonly SpanEnd[] | undefined) {
  const pending = new Map<string, { start: T; span: SpanEnd }>()
  const ranges: { start: T; end: T; span: SpanEnd }[] = []
  for (const beat of beats) {
    for (const span of ends(beat) ?? []) {
      if (!span.end) {
        pending.set(span.id, { start: beat, span })
        continue
      }
      const origin = pending.get(span.id)
      if (!origin || origin.span.kind !== span.kind) continue
      ranges.push({ ...origin, end: beat })
      pending.delete(span.id)
    }
  }
  return ranges
}
