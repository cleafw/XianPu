export type Language = 'zh' | 'en'
export type LanguagePreference = Language | 'system'
export type TextKey = keyof typeof english
type Values = Record<string, string | number>
export type Message = { key: TextKey; values?: Values; detail?: unknown }
export const languageKey = 'xianpu.language.v1'
export const appName: TextKey = '叶子弦谱'

export function translate(language: Language, key: TextKey, values?: Values) {
  return (language === 'zh' ? key : english[key]).replace(/\{(\w+)\}/g, (token, field: string) => String(values?.[field] ?? token))
}
export type Translate = (key: TextKey, values?: Values) => string
export const message = (key: TextKey, values?: Values, detail?: unknown): Message => ({ key, values, detail })
export function displayMessage(t: Translate, value: Message | null) {
  if (!value) return ''
  if (value.detail === undefined) return t(value.key, value.values)
  const detail = value.detail instanceof Error ? value.detail.message : String(value.detail)
  const localized = Object.hasOwn(english, detail) ? t(detail as TextKey) : detail
  return t(value.key, value.values) + ' ' + localized
}
export const languageOf = (locale: string): Language => /^zh(?:[-_]|$)/i.test(locale) ? 'zh' : 'en'
export function readLanguagePreference(): LanguagePreference {
  try {
    const value = localStorage.getItem(languageKey)
    if (value === 'zh' || value === 'en') return value
  } catch { /* System language remains available. */ }
  return 'system'
}
export const LanguageContext = createContext<Language>('en')
export function useLanguage() {
  const language = useContext(LanguageContext)
  const t: Translate = (key, values) => translate(language, key, values)
  return { language, t }
}
