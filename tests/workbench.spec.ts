  const choose = (name: string) => sidebar.getByRole('button', { name, exact: true })
  const remove = (name: string) => choose('删除分谱 ' + name)
  const confirmation = page.getByRole('dialog', { name: '删除分谱' })
  await choose('吉他六线谱').click()
  await remove('吉他六线谱').click()
