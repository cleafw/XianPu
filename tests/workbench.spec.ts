test('saves custom watermarks and renders them in the score and on every exported page', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '打开弹唱示例' }).click()
  const score = page.locator('.canvas .score-render')
  await expect(score.locator('svg').first()).toBeVisible()
  await expect(score).not.toContainText('rendered by alphaTab')
  await expect(score).not.toContainText('alphaTab.net')
  await expect(score.locator('.score-watermark')).toHaveCount(0)

  const settings = page.getByRole('button', { name: '曲谱设置', exact: true })
  const close = page.getByRole('dialog').getByRole('button', { name: '关闭' })
  const input = page.getByRole('textbox', { name: '水印文字', exact: true })
  const text = '叶子弦谱 <校样>'
  await settings.click()
  await input.fill(text)
  await close.click()
  await expect(score.locator('.score-watermark')).toHaveText(text)
  await expect(score.locator('.score-watermark text')).toHaveAttribute('transform', 'rotate(-28 300 200)')
  await settings.click()
  await page.getByLabel('水印样式').selectOption('tiled')
  await page.getByRole('slider', { name: '水印大小' }).fill('65')
  await page.getByRole('slider', { name: '旋转角度' }).fill('35')
  await page.getByRole('slider', { name: '不透明度' }).fill('22')
  await close.click()
  await expect(score.locator('.score-watermark pattern')).toHaveAttribute('patternTransform', 'rotate(35)')
  await expect(score.locator('.score-watermark text')).toHaveAttribute('font-size', '13')
  await expect(score.locator('.score-watermark text')).toHaveAttribute('fill-opacity', '0.22')
  const saved = page.waitForEvent('download')
  await page.getByRole('button', { name: '保存 •' }).click()
  const bytes = await readFile((await (await saved).path())!)
  const savedProject = parseProject(bytes.toString())
  expect(savedProject.watermark).toBe(text)
  expect(savedProject.watermarkStyle).toEqual({ layout: 'tiled', size: 65, angle: 35, opacity: 22 })
  await page.locator('input[type=file]').setInputFiles({ name: 'watermarked.xianpu', mimeType: 'application/json', buffer: bytes })
  await expect(score.locator('.score-watermark')).toHaveText(text)

  await page.getByRole('navigation').getByRole('button', { name: '简谱', exact: true }).click()
  await expect(score.locator('.score-watermark')).toHaveText(text)
  await page.getByLabel('每页谱行').selectOption('1')
  await page.getByRole('button', { name: '导出', exact: true }).click()
  const preview = page.getByRole('dialog').locator('.print-page')
  await expect(preview.locator('.score-watermark')).toHaveText([text, text])
  await expect(preview.locator('.score-watermark pattern')).toHaveCount(2)
  expect(new Set(await preview.locator('.score-watermark pattern').evaluateAll((patterns) => patterns.map(({ id }) => id))).size).toBe(2)
  await expect(preview.last()).not.toContainText('rendered by alphaTab')
  await expect(preview.last()).not.toContainText('alphaTab.net')
  const print = page.locator('.print-only .print-page')
  await expect(print.locator('.score-watermark')).toHaveText([text, text])
  const pdf = await page.pdf({ preferCSSPageSize: true })
  expect(pdf.toString('latin1').match(/\/Type \/Page\b/g)).toHaveLength(2)

  const pngChanges = await preview.first().evaluate(async (paper) => {
    const path = '/src/exportImage.ts'
    const { renderPng } = await import(path)
    const before = new Uint8Array(await (await renderPng(paper)).arrayBuffer())
    paper.querySelector('.score-watermark')!.remove()
    const after = new Uint8Array(await (await renderPng(paper)).arrayBuffer())
    return before.length !== after.length || before.some((byte, index) => byte !== after[index])
  })
  expect(pngChanges).toBe(true)
  await close.click()
  await settings.click()
  await input.fill('   ')
  await close.click()
  await expect(score.locator('.score-watermark')).toHaveCount(0)
})

