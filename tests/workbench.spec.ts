  await expect(choose('吉他六线谱')).toHaveAttribute('aria-current', 'page')
  await choose('总谱').click()
  await remove('吉他六线谱').click()
  await confirmation.getByRole('button', { name: '删除分谱', exact: true }).click()
  await expect(choose('吉他六线谱')).toHaveCount(0)
  await expect(choose('总谱')).toHaveAttribute('aria-current', 'page')
