  await page.getByLabel('每行小节').selectOption('2')
  await page.getByLabel('每页谱行').selectOption('1')

  await bar(1).click()
  await bar(3).click({ modifiers: ['Shift'] })
  await page.getByRole('button', { name: '前奏括号', exact: true }).click()
  const intro = page.getByRole('dialog', { name: '前奏括号' })
