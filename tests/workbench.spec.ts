  await choose('五线谱').click()
  await remove('五线谱').click()
  await confirmation.getByRole('button', { name: '删除分谱', exact: true }).click()
  await expect(choose('简谱')).toHaveAttribute('aria-current', 'page')
  await choose('总谱').click()
  await expect(remove('简谱')).toBeDisabled()
  await expect(page.getByRole('button', { name: '简谱位置 1' })).toContainText('C')
  await expect(page.getByRole('button', { name: '五线谱位置 1' })).toHaveCount(0)
